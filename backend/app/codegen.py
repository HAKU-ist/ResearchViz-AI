def execute_code(code_path: Path, csv_path: Path, image_path: Path, svg_path: Path | None = None) -> None:
    env = {**os.environ, "MPLBACKEND": "Agg"}
    command = [sys.executable, str(code_path), "--input", str(csv_path), "--output", str(image_path)]
    if svg_path:
        command.extend(["--svg-output", str(svg_path)])
    result = subprocess.run(
        command,
        capture_output=True, text=True, timeout=60, env=env,
    )
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip()[-2000:] or "绘图进程执行失败")
    if not image_path.exists() or image_path.stat().st_size == 0:
        raise RuntimeError("绘图完成但未生成有效图片")
    if svg_path and (not svg_path.exists() or svg_path.stat().st_size == 0):
        raise RuntimeError("绘图完成但未生成有效 SVG")
