def apply_filter(df, item):
    column, operator = item["column"], item["operator"]
    if column not in df.columns:
        raise ValueError(f"Missing filter column: {{column}}")
    series = df[column]
    numeric = pd.to_numeric(series, errors="coerce")
    value, values = item.get("value"), item.get("values") or []
    if operator in ("eq", "ne"):
        if isinstance(value, (int, float)) and numeric.notna().any():
            mask = (numeric - float(value)).abs() <= 1e-9
        else:
            mask = series.astype(str) == str(value)
        return df[~mask if operator == "ne" else mask]
    if operator in ("in", "not_in"):
        mask = series.astype(str).isin([str(item) for item in values])
        return df[~mask if operator == "not_in" else mask]
    if operator == "between":
        if len(values) != 2:
            raise ValueError("between requires exactly two values")
        return df[numeric.between(float(values[0]), float(values[1]), inclusive="both")]
    target = float(value)
    masks = {{"gt": numeric > target, "gte": numeric >= target, "lt": numeric < target, "lte": numeric <= target}}
    return df[masks[operator]]

def aggregate_data(df, aggregation):
    if not aggregation:
        return df
    keys = aggregation.get("group_by") or []
    outputs = []
    for metric in aggregation.get("metrics") or []:
        source, output, function = metric["source"], metric["output"], metric["function"]
        if source not in df.columns:
            raise ValueError(f"Missing aggregation source: {{source}}")
        if function == "none":
            part = df[keys + [source]].rename(columns={{source: output}})
        elif keys:
            grouped = df.groupby(keys, dropna=False, sort=False)[source]
            part = getattr(grouped, function)().reset_index(name=output)
            error = metric.get("error", "none")
            if error != "none":
                error_output = metric.get("error_output")
                if not error_output:
                    raise ValueError("error_output is required")
                error_values = grouped.std()
                if error == "sem":
                    error_values = error_values / grouped.count().pow(0.5)
                part = part.merge(error_values.reset_index(name=error_output), on=keys, how="left")
        else:
            values = pd.to_numeric(df[source], errors="coerce").dropna()
            center = len(values) if function == "count" else getattr(values, function)()
            row = {{output: center}}
            error = metric.get("error", "none")
            if error != "none":
                deviation = values.std()
                row[metric["error_output"]] = deviation / math.sqrt(len(values)) if error == "sem" and len(values) else deviation
            part = pd.DataFrame([row])
        outputs.append(part)
    if not outputs:
        return df[keys].drop_duplicates() if keys else df
    result = outputs[0]
    for part in outputs[1:]:
        result = result.merge(part, on=keys, how="outer") if keys else pd.concat([result, part], axis=1)
    return result

def apply_canvas_layout(fig, ax, title_artist, legend, style):
    objects = {{item["id"]: item for item in style.get("canvas_objects") or []}}
    plot = objects.get("plot-area")
    if plot:
        ax.set_visible(plot.get("visible", True))
        if plot.get("visible", True):
            ax.set_position([
                plot["x"],
                1 - plot["y"] - plot["height"],
                plot["width"],
                plot["height"],
            ])
    text_artists = {{
        "chart-title": title_artist,
        "x-axis-label": ax.xaxis.label,
        "y-axis-label": ax.yaxis.label,
    }}
    for object_id, artist in text_artists.items():
        item = objects.get(object_id)
        if not item:
            continue
        artist.set_visible(item.get("visible", True))
        if not item.get("visible", True):
            continue
        artist.set_transform(fig.transFigure)
        artist.set_position((
            item["x"] + item["width"] / 2,
            1 - item["y"] - item["height"] / 2,
        ))
        artist.set_rotation(item.get("rotation", 0))
        scale = item["height"] / max(item.get("base_height", item["height"]), .001)
        artist.set_fontsize(max(6, min(72, artist.get_fontsize() * scale)))
    legend_item = objects.get("chart-legend")
    if legend is not None and legend_item:
        legend.set_visible(legend_item.get("visible", True))
        if legend_item.get("visible", True):
            legend.set_bbox_to_anchor((
                legend_item["x"] + legend_item["width"] / 2,
                1 - legend_item["y"] - legend_item["height"] / 2,
            ), transform=fig.transFigure)
            legend._loc = 10
            scale = legend_item["height"] / max(legend_item.get("base_height", legend_item["height"]), .001)
            for text in list(legend.get_texts()) + ([legend.get_title()] if legend.get_title() else []):
                text.set_fontsize(max(6, min(48, text.get_fontsize() * scale)))
            legend.set_transform(matplotlib.transforms.Affine2D().rotate_deg_around(0, 0, legend_item.get("rotation", 0)))

def main(input_path: str, output_path: str, svg_output_path: str | None = None) -> None:
    df = pd.read_csv(input_path)
    query, chart = PLAN["data_query"], PLAN["chart"]
    for item in query.get("filters") or []:
        df = apply_filter(df, item)
    if df.empty:
        raise ValueError("No rows remain after filters")

    selection = query.get("selection") or {{"mode": "all"}}
    if selection.get("mode") in ("first", "last"):
        order_by = selection.get("order_by")
        if not order_by or order_by not in df.columns:
            raise ValueError("selection.order_by is missing")
        df = df.sort_values(order_by, kind="stable")
        keys = selection.get("group_by") or []
        if keys:
            grouped = df.groupby(keys, dropna=False, sort=False)
            df = grouped.head(1) if selection["mode"] == "first" else grouped.tail(1)
        else:
            df = df.head(1) if selection["mode"] == "first" else df.tail(1)

    reshape = query.get("reshape") or {{"mode": "none"}}
    if reshape.get("mode") == "wide_to_long":
        id_columns = reshape.get("id_columns") or []
        value_columns = reshape.get("value_columns") or []
        missing = [column for column in id_columns + value_columns if column not in df.columns]
        if missing:
            raise ValueError(f"Missing reshape columns: {{missing}}")
        for column in value_columns:
            df[column] = pd.to_numeric(df[column], errors="coerce")
        df = df.melt(
            id_vars=id_columns,
            value_vars=value_columns,
            var_name=reshape["variable_name"],
            value_name=reshape["value_name"],
        )

    df = aggregate_data(df, query.get("aggregation"))
    x, y, group, error_y = chart["x"], chart["y"], chart.get("group"), chart.get("error_y")
    required = [x, y] + ([group] if group else []) + ([error_y] if error_y else [])
    missing = [column for column in required if column not in df.columns]
    if missing:
        raise ValueError(f"Missing chart columns: {{missing}}")
    df[y] = pd.to_numeric(df[y], errors="coerce")
    if error_y:
        df[error_y] = pd.to_numeric(df[error_y], errors="coerce")
    df = df.dropna(subset=[x, y])
    if df.empty:
        raise ValueError("No data remains for chart")

    style = chart.get("style") or {{}}
    palette = style.get("palette") or ["#126149", "#d28b36", "#5378a5", "#a65353", "#7b62a3"]
    plt.rcParams.update({{"font.size": style.get("font_size", 11)}})
    fig, ax = plt.subplots(figsize=(style.get("figure_width", 7.2), style.get("figure_height", 4.8)))
    ax.set_gid("plot-area")
    fig.patch.set_facecolor(style.get("background_color", "#ffffff"))
    ax.set_facecolor(style.get("background_color", "#ffffff"))
    chart_type = chart["chart_type"]
    groups = list(df.groupby(group, dropna=False, sort=False)) if group else [(None, df)]
    if chart_type == "line":
        for index, (label, part) in enumerate(groups):
            part = part.sort_values(x)
            color = palette[index % len(palette)]
            marker = None if style.get("marker", "o") == "none" else style.get("marker", "o")
            line, = ax.plot(part[x], part[y], marker=marker, linewidth=style.get("line_width", 2), color=color, label=str(label) if label is not None else None)
            line.set_gid(f"series-{{index}}")
            if error_y and part[error_y].notna().any():
                error = part[error_y].fillna(0)
                ax.fill_between(part[x], part[y] - error, part[y] + error, color=color, alpha=.15)
    elif chart_type == "bar":
        if group:
            df.pivot(index=x, columns=group, values=y).plot.bar(ax=ax, width=style.get("bar_width", .82), color=palette)
        else:
            errors = df[error_y].fillna(0) if error_y else None
            ax.bar(df[x].astype(str), df[y], yerr=errors, color=palette[0], width=style.get("bar_width", .82), capsize=4 if error_y else 0)
    elif chart_type == "scatter":
        for index, (label, part) in enumerate(groups):
            points = ax.scatter(part[x], part[y], color=palette[index % len(palette)], alpha=.72, label=str(label) if label is not None else None)
            points.set_gid(f"series-{{index}}")
    elif chart_type == "box":
        if group:
            labels, values = zip(*[(str(key), part[y].dropna().values) for key, part in groups])
            ax.boxplot(values, tick_labels=labels)
        else:
            ax.boxplot(df[y].dropna().values)
    bar_series_index = 0
    for container in ax.containers:
        patches = [patch for patch in container if patch is not None and patch.__class__.__name__ == "Rectangle"]
        if patches:
            for patch in patches:
                patch.set_gid(f"series-{{bar_series_index}}")
            bar_series_index += 1
    title_artist = ax.set_title(chart["title"], fontsize=style.get("title_size", 14))
    title_artist.set_gid("chart-title")
    ax.set_xlabel(chart["x_label"])
    ax.set_ylabel(chart["y_label"])
    ax.xaxis.label.set_gid("x-axis-label")
    ax.yaxis.label.set_gid("y-axis-label")
    ax.tick_params(axis="x", labelrotation=style.get("x_tick_rotation", 0))
    ax.grid(style.get("grid", True), alpha=.22)
    legend = None
    if group and chart_type != "box":
        if style.get("legend_x") is not None and style.get("legend_y") is not None:
            legend = ax.legend(title=group, frameon=False, loc="center", bbox_to_anchor=(style["legend_x"], style["legend_y"]), bbox_transform=ax.transAxes)
        else:
            legend = ax.legend(title=group, frameon=False, loc=style.get("legend_position", "best"))
        legend.set_gid("chart-legend")
        for index, handle in enumerate(legend.legend_handles):
            handle.set_gid(f"legend-series-{{index}}")
    fig.tight_layout()
    apply_canvas_layout(fig, ax, title_artist, legend, style)
    fig.savefig(output_path, dpi=chart["dpi"], facecolor=style.get("background_color", "#ffffff"))
    if svg_output_path:
        fig.savefig(svg_output_path, format="svg", facecolor=style.get("background_color", "#ffffff"))
    plt.close(fig)

